// Package buildinfo хранит сведения о собранной версии приложения.
//
// На последующих этапах CI передаст реальные значения через флаг компоновщика
// -ldflags. Значения по умолчанию позволяют удобно запускать сервис локально.
package buildinfo

var (
	// Version содержит человекочитаемую версию приложения.
	Version = "development"

	// Commit содержит SHA Git-коммита, из которого собран бинарный файл.
	Commit = "unknown"

	// BuildTime содержит время сборки в формате RFC 3339.
	BuildTime = "unknown"
)

//  1. Локальная сборка использует безопасные и понятные значения по умолчанию.
//  2. Production-сборка заменяет значения посредством go build -ldflags.
//  3. На Этапе 2 gRPC-сервис будет выводить эти сведения при запуске и в метриках.
